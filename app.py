"""DocuMind AI - Chat with Your PDF (Streamlit UI)."""
from __future__ import annotations

import logging
from dataclasses import replace

import streamlit as st

from config import load_settings
from pdf_processor import PDFError, chunk_pages, extract_pages
from rag_pipeline import RAGError, RAGPipeline

logging.basicConfig(level=logging.INFO)  # logs go to the server console, never to the UI

st.set_page_config(page_title="DocuMind AI", page_icon="📄", layout="centered")

BASE = load_settings()


def init_state() -> None:
    ss = st.session_state
    ss.setdefault("pipeline", None)
    ss.setdefault("indexed_key", None)  # (file hash, chunk_size, overlap) of what is in ChromaDB
    ss.setdefault("doc_info", None)
    ss.setdefault("messages", [])
    ss.setdefault("uploader_nonce", 0)  # bumping this resets the uploader widget


def reset_document() -> None:
    ss = st.session_state
    if ss.pipeline is not None:
        ss.pipeline.reset()
    ss.pipeline = ss.indexed_key = ss.doc_info = None
    ss.messages = []


def process_upload(uploaded, chunk_size: int, overlap: int) -> None:
    """Parse -> chunk -> embed -> store. Skipped when the same file+params are already indexed."""
    ss = st.session_state
    data = uploaded.getvalue()
    try:
        result = extract_pages(data, uploaded.name, BASE.max_pdf_mb, BASE.max_pages)
    except PDFError as e:
        reset_document()
        st.error(str(e))
        return

    key = (result.file_hash, chunk_size, overlap)
    if ss.indexed_key == key and ss.pipeline is not None:
        return  # normal Streamlit rerun: do NOT re-embed

    # New document or new chunk settings => fresh index, fresh conversation.
    reset_document()
    try:
        chunks = chunk_pages(result.pages, chunk_size, overlap)
    except ValueError as e:
        st.error(str(e))
        return
    pipeline = RAGPipeline(replace(BASE, chunk_size=chunk_size, chunk_overlap=overlap))
    with st.status("Processing document...", expanded=True) as status:
        try:
            st.write(f"Extracted text from {result.pages_with_text}/{result.total_pages} pages")
            st.write(f"Created {len(chunks)} chunks; generating embeddings...")
            pipeline.index(chunks, result.file_hash)
        except RAGError as e:
            status.update(label="Processing failed", state="error")
            st.error(str(e))
            return
        status.update(label="Document ready", state="complete", expanded=False)
    ss.pipeline, ss.indexed_key = pipeline, key
    ss.doc_info = {"name": result.filename, "pages": result.total_pages,
                   "text_pages": result.pages_with_text, "chunks": len(chunks)}


def render_sources(sources) -> None:
    with st.expander(f"Retrieved source chunks ({len(sources)})"):
        for i, s in enumerate(sources, 1):
            st.markdown(f"**{i}. {s.filename} - page {s.page}**  ·  similarity `{s.similarity:.2f}`")
            st.text(s.text)


def main() -> None:
    init_state()
    ss = st.session_state

    st.title("📄 DocuMind AI")
    st.caption("Chat with your PDF. Answers come only from the document - retrieved with "
               "embeddings + ChromaDB, generated by Gemini.")

    if not BASE.google_api_key:
        st.error("GOOGLE_API_KEY is missing. Copy `.env.example` to `.env`, add your key and restart.")

    with st.sidebar:
        st.header("Settings")
        chunk_size = st.number_input("Chunk size (chars)", 200, 4000, BASE.chunk_size, 100)
        overlap = st.number_input("Chunk overlap (chars)", 0, 1000, BASE.chunk_overlap, 25)
        top_k = st.slider("Chunks to retrieve (k)", 1, 10, BASE.top_k)
        min_sim = st.slider("Relevance threshold (cosine similarity)", 0.0, 1.0, BASE.min_similarity, 0.05,
                            help="If the best chunk scores below this, the LLM is not called.")
        st.caption("Chunk settings re-index the document; k and threshold apply instantly.")
        if st.button("🗑️ Clear conversation", use_container_width=True):
            ss.messages = []
            st.rerun()

    uploaded = st.file_uploader("Upload a PDF", type=["pdf"], key=f"uploader_{ss.uploader_nonce}")

    if uploaded is None:
        if ss.pipeline is not None:
            reset_document()  # file removed -> forget the old document completely
        st.info("Upload a PDF to start asking questions.")
    elif BASE.google_api_key:
        if int(overlap) >= int(chunk_size):
            st.error("Chunk overlap must be smaller than chunk size.")
        else:
            process_upload(uploaded, int(chunk_size), int(overlap))

    ready = ss.pipeline is not None
    if ready:
        d = ss.doc_info
        st.success(f"**{d['name']}** · {d['pages']} pages ({d['text_pages']} with text) · {d['chunks']} chunks")
        # k / threshold are query-time only, so update without re-embedding
        ss.pipeline.settings = replace(ss.pipeline.settings, top_k=top_k, min_similarity=min_sim)
        if st.button("📂 Upload another PDF"):
            reset_document()
            ss.uploader_nonce += 1
            st.rerun()

    for m in ss.messages:
        with st.chat_message(m["role"]):
            st.markdown(m["content"])
            if m.get("sources"):
                render_sources(m["sources"])

    question = st.chat_input("Ask a question about your PDF..." if ready else "Process a PDF first",
                             disabled=not ready)
    if question:
        if not question.strip():
            st.warning("Please type a question.")
            return
        ss.messages.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)
        with st.chat_message("assistant"):
            with st.spinner("Searching document and generating answer..."):
                try:
                    ans = ss.pipeline.answer(question)
                    msg = {"role": "assistant", "content": ans.text, "sources": ans.sources}
                    if ans.reason == "below_threshold":
                        msg["content"] += f"\n\n_(Best match similarity {ans.best_similarity:.2f} < threshold {min_sim:.2f}; no answer generated.)_"
                except RAGError as e:
                    msg = {"role": "assistant", "content": f"⚠️ {e}"}
                except Exception:  # noqa: BLE001 - never leak internals to the UI
                    logging.exception("Unexpected error")
                    msg = {"role": "assistant", "content": "⚠️ Something went wrong. Please try again."}
            st.markdown(msg["content"])
            if msg.get("sources"):
                render_sources(msg["sources"])
        ss.messages.append(msg)


main()
